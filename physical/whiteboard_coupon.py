#!/usr/bin/env python3
"""
Whiteboard kit test coupon: the smallest print that answers the open questions before a whole set is printed.

  coupon_cups.stl      a plate with three cups of radius 2.6 / 2.7 / 2.85 mm (the design is 2.7), each with its joint-magnet pocket
  coupon_pockets.stl   a plate with three cups of 2.7 mm and joint-magnet pockets of 3.1 / 3.2 / 3.35 mm for a 3 x 1.5 mm magnet (design: 3.2)
  coupon_board.stl     a plate with three board-magnet pockets of 8.1 / 8.2 / 8.4 mm for an 8 x 2 mm magnet (design: 8.2)
  coupon_stick_47/48/49.stl   20 mm sticks with ball holes of 4.7 / 4.8 / 4.9 mm for a 5 mm steel ball (design: 4.8)
  plus real parts from the kit: tile_N1 (an NP), tile_N2 (an N0), tile_abbr_small, stick_20, stick_40 (copied from whiteboard/)

Run from the repo root:  python3 physical/whiteboard_coupon.py
"""
import json, os, shutil, sys, math
import numpy as np
import trimesh
from trimesh.creation import box as tbox, cylinder, icosphere
from trimesh.boolean import difference, intersection

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import concept as K
import hinge as H
import whiteboard as W

OUT = os.path.join(HERE, 'whiteboard_coupon')
os.makedirs(OUT, exist_ok=True)
T = K.THICK


def plate(w, h):
    return H.fix(tbox(extents=[w, h, T]) if False else _plate(w, h))


def _plate(w, h):
    m = tbox(extents=[w, h, T]); m.apply_translation([0, 0, T / 2]); return m


def cups_plate(radii, pocket_ds, board_ds=None, w=50.0, h=18.0):
    m = _plate(w, h)
    cuts = []
    xs = [-14.0, 0.0, 14.0]
    for x, r, pd in zip(xs, radii, pocket_ds):
        s = icosphere(subdivisions=3, radius=r); s.apply_translation([x, 0, T + 0.9]); cuts.append(s)
        p = cylinder(radius=pd / 2, height=3.9, sections=32); p.apply_translation([x, 0, 3.8 / 2 - 0.1]); cuts.append(p)
    return H.fix(difference([m] + cuts, engine='manifold'))


def board_plate(ds, w=58.0, h=14.0):
    m = _plate(w, h)
    cuts = []
    for x, d in zip((-19.0, 0.0, 19.0), ds):
        p = cylinder(radius=d / 2, height=2.2, sections=40); p.apply_translation([x, 0, 0.9]); cuts.append(p)
    return H.fix(difference([m] + cuts, engine='manifold'))


def stick20(hole_d):
    from trimesh.creation import box as tb
    L = 20.0
    bar = tb(extents=[L + 8.0, 4.0, 3.0]); bar.apply_translation([L / 2, 0, 1.5])
    cuts = []
    for x in (0.0, L):
        c = cylinder(radius=hole_d / 2, height=6.0, sections=48); c.apply_translation([x, 0, 1.5 - 0.6]); cuts.append(c)
    return H.fix(difference([bar] + cuts, engine='manifold'))


def main():
    files = {}
    files['coupon_cups.stl'] = cups_plate((2.6, 2.7, 2.85), (3.2, 3.2, 3.2))
    files['coupon_pockets.stl'] = cups_plate((2.7, 2.7, 2.7), (3.1, 3.2, 3.35))
    files['coupon_board.stl'] = board_plate((8.1, 8.2, 8.4))
    for d in (4.7, 4.8, 4.9):
        files[f'coupon_stick_{int(round(d * 10))}.stl'] = stick20(d)
    report = {}
    for f, m in files.items():
        assert m.is_watertight, f
        m.export(os.path.join(OUT, f))
        report[f] = [round(float(x), 1) for x in m.extents]
    for f in ('tile_N1.stl', 'tile_N2.stl', 'tile_abbr_small.stl', 'stick_20.stl', 'stick_40.stl'):
        shutil.copy(os.path.join(HERE, 'whiteboard', f), os.path.join(OUT, 'kit_' + f))
        report['kit_' + f] = [round(float(x), 1) for x in trimesh.load(os.path.join(OUT, 'kit_' + f)).extents]
    # a 5 mm ball seated in each cup (centre at the cup's centre) must not touch the plate
    ball = icosphere(subdivisions=3, radius=2.5)
    seat = {}
    for f in ('coupon_cups.stl', 'coupon_pockets.stl'):
        plate_m = files[f]
        for x in (-14.0, 0.0, 14.0):
            b = ball.copy(); b.apply_translation([x, 0, T + 0.9])
            r = intersection([plate_m, b], engine='manifold')
            seat[f'{f} x={x:+.0f}'] = float(r.volume) if len(r.faces) else 0.0
    # a 5 mm ball is pressed into a stick hole: the hole must be smaller than the ball
    bad = {k: v for k, v in seat.items() if v != 0.0}
    print('ball in cup (should all be 0 mm3):', 'ok' if not bad else bad)
    print('files:', len(report))
    json.dump(dict(files=report, seat=seat), open(os.path.join(OUT, 'coupon.json'), 'w'), indent=1)
    write_docs()


def write_docs():
    s = """# Whiteboard kit: test coupon and order sheet

Generated by `physical/whiteboard_coupon.py`. Files: `physical/whiteboard_coupon/` (11 STLs).

## What it is for

Nothing in the whiteboard kit has been printed. Four numbers decide whether it works, and each can be settled with a few grams of plastic:

1. **Does the steel ball seat in the cup and does the magnet behind the cup hold it?** (`coupon_cups.stl`, `coupon_pockets.stl`)
2. **Does the joint magnet fit its pocket?** (`coupon_pockets.stl`: 3.1 / 3.2 / 3.35 mm for a 3 x 1.5 mm magnet)
3. **Does the board magnet fit its pocket, and does it hold the tile on *your* whiteboard?** (`coupon_board.stl`: 8.1 / 8.2 / 8.4 mm for an 8 x 2 mm magnet)
4. **Does the steel ball press into the stick?** (`coupon_stick_47/48/49.stl`: 4.7 / 4.8 / 4.9 mm holes for a 5 mm ball)

The last five files are real kit parts: an NP tile, an N0 tile, a small abbreviation triangle and a 20 mm and a 40 mm stick (prefixed `kit_`), so one phrase can be built and moved at full size.

## What to print

PETG if available. 0.2 mm layers, 3 perimeters, about 40% infill, no supports, no brim. Print each plate and tile **back-down** (the side with the large pockets on the bed) and each stick flat. Two copies of every file is a good idea, in case a pocket is out by a tenth of a millimetre.

## What to buy for the test

| Item | How many | For |
|---|---|---|
| Neodymium disc magnet 8 x 2 mm (N35) | 8 | board magnets: coupon plate, NP tile, abbreviation triangle |
| Neodymium disc magnet 6 x 2 mm | 6 | the N0 tile, the triangle's corners |
| Neodymium disc magnet 3 x 1.5 mm | 25 | joint magnets |
| Steel ball 5 mm (a bearing ball, not a magnet) | 20 | stick ends |
| A steel-backed whiteboard or a steel sheet | the board you will use | the real test |

All sizes are the ones the pockets are drawn for. If a shop sells 8 x 1.5 mm or 6 x 1.5 mm, they will fit.

## What to do with it, and what to write down

1. Push a 3 x 1.5 mm magnet into each pocket of `coupon_pockets` and each pocket of `coupon_cups` (from the back, up against the thin wall behind the cup). Note which of 3.1 / 3.2 / 3.35 is a snug press fit.
2. Press a 5 mm steel ball into a hole of each coupon stick (a vice or pliers, gently; the ball stands proud of the bar by about 1 mm on one face). Note which of 4.7 / 4.8 / 4.9 holds it without cracking the stick.
3. Seat a stick's ball in each cup of `coupon_cups` (the ball goes in the cup with the stick lying over the plate). Note which cup (2.6 / 2.7 / 2.85) holds the ball in place on a vertical board, and whether the stick turns freely.
4. Push 8 x 2 mm magnets into `coupon_board`. Stick it on your whiteboard. Note which pocket is snug, and whether the plate stays up on a vertical board.
5. Build the NP tile with a stick to the N0 tile and a stick to the triangle, put it on the board, and slide the whole phrase by one tile. Note whether the joints pull apart, and whether the phrase flops.

Send me those numbers and I will set the pocket, cup and hole sizes in the real design.

## Order sheet (to give to a print shop or a makerspace)

**Parts:** the 11 STL files in this folder, two copies of each (22 parts). Total plastic: about 30 g.
**Material:** PETG preferred; PLA acceptable for this test only.
**Settings:** 0.2 mm layer height, 3 perimeters, about 40% infill, no supports. Back-down for plates and tiles; sticks flat.
**Tolerance:** the pockets and holes are drawn at their final sizes. Please do not scale parts, and please tell me which printer and nozzle was used.
**Not part of the print:** magnets, steel balls and the whiteboard are bought separately (the table above).
"""
    open(os.path.join(HERE, 'WHITEBOARD_COUPON.md'), 'w').write(s)


if __name__ == '__main__':
    main()
